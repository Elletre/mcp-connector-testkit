#!/usr/bin/env python
"""Write the results tables in docs/agent-evals.md from the committed runs.

    uv run python tools/eval_results.py

Reads `summary.json` of each run listed in RUNS and the `compare-*.json` files
next to them, and replaces the block between the RESULTS markers. Nothing in
that block is typed by hand, so every number in it can be traced to a file.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evals/results"
DOC = ROOT / "docs/agent-evals.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"

BASELINE = "2026-09-18-llama3-8b-baseline"
RUNS = {
    "clean connector": BASELINE,
    "`vague-tool-descriptions`": "2026-09-18-llama3-8b-vague-tool-descriptions",
    "`untrusted-content-unmarked`": "2026-09-18-llama3-8b-untrusted-content-unmarked",
}
SAMPLED = "2026-09-18-llama3-8b-baseline-temperature-0.8"
COMPARISONS = {
    "`vague-tool-descriptions`": "compare-vague-tool-descriptions.json",
    "`untrusted-content-unmarked`": "compare-untrusted-content-unmarked.json",
}


def load(name: str) -> dict[str, Any]:
    return dict(json.loads((RESULTS / name / "summary.json").read_text()))


def rate(block: dict[str, float]) -> str:
    return f"{block['estimate']:.0%} ({block['low']:.0%}–{block['high']:.0%})"


def points(value: float) -> str:
    return f"{value * 100:+.0f}".replace("-", "−")


def delta(comparison: dict[str, Any]) -> str:
    overall = comparison["overall"]
    text = f"{points(overall['estimate'])} [{points(overall['low'])}, {points(overall['high'])}]"
    return f"**{text} — regression**" if comparison["regressed"] else f"{text} — no significant change"


def render() -> str:
    summaries = {label: load(name) for label, name in RUNS.items()}
    comparisons = {label: json.loads((RESULTS / file).read_text()) for label, file in COMPARISONS.items()}
    base = summaries["clean connector"]
    lines = [
        "*Generated by `tools/eval_results.py` from `evals/results/`; do not edit by hand.*",
        "",
        f"Model `{base['model']}` through the prompted-JSON adapter · {base['cases']} cases × "
        f"{base['repeats']} repeats per run · recorded {base['started_at'][:10]} on {base['machine']}.",
        "",
        "| Connector | Pass rate (95% interval over cases) | pass^k | Same verdict every repeat "
        "| Unsafe | Change in pass rate, points [95% interval] |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for label, summary in summaries.items():
        change = delta(comparisons[label]) if label in comparisons else "—"
        lines.append(
            f"| {label} | {rate(summary['pass_rate'])} | {summary['pass_hat_k']:.0%} | "
            f"{summary['repeat_agreement']:.0%} | {rate(summary['unsafe_rate'])} | {change} |"
        )

    lines += [
        "",
        "By category (pass rate; the intervals are wide because each category has three to five cases):",
        "",
        "| Category | Cases | " + " | ".join(summaries) + " |",
        "| --- | ---: | " + " | ".join("---" for _ in summaries) + " |",
    ]
    for category, block in base["categories"].items():
        cells = [rate(summary["categories"][category]["pass_rate"]) for summary in summaries.values()]
        lines.append(f"| {category} | {block['cases']} | " + " | ".join(cells) + " |")

    sampled_path = RESULTS / SAMPLED / "summary.json"
    if sampled_path.exists():
        sampled = load(SAMPLED)
        lines += [
            "",
            "The clean connector again, sampled instead of greedy:",
            "",
            "| Run | Pass rate | pass^k | Same verdict every repeat |",
            "| --- | --- | --- | --- |",
            f"| {base['model']} | {rate(base['pass_rate'])} | {base['pass_hat_k']:.0%} | "
            f"{base['repeat_agreement']:.0%} |",
            f"| {sampled['model']} | {rate(sampled['pass_rate'])} | {sampled['pass_hat_k']:.0%} | "
            f"{sampled['repeat_agreement']:.0%} |",
        ]
    lines += [
        "",
        "Runs: "
        + " · ".join(f"[`{name}`](../evals/results/{name})" for name in [*RUNS.values(), SAMPLED])
        + ".",
    ]
    return "\n".join(lines)


def main() -> None:
    text = DOC.read_text()
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    DOC.write_text(f"{head}{START}\n{render()}\n{END}{tail}")
    print(f"wrote the results block in {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
